-- case when
-- Categorize tracks based on their price.
select track_id,unit_price,
 case
       WHEN unit_price >= 1.20 THEN 'Expensive'
	   WHEN unit_price >= 0.99 THEN 'Moderate'
       else "cheap"
    end as price_category
    from track;

-- Categorize invoices based on their total amount. 
select invoice_id,total, 
case
    when total>=3 then "high"
    when total>= 2 then "medium"
    else "low"
    end as invoice_category
    from invoice;

 -- Categorize customers as Domestic or International.    
 SELECT first_name,
       country,
       CASE
           WHEN country = 'India' THEN 'Domestic'
           ELSE 'International'
       END AS customer_type
FROM customer;

--  Categorize tracks as Premium or Regular.
SELECT name,
       unit_price,
       CASE
           WHEN unit_price >= 1.20 THEN 'Premium'
           ELSE 'Regular'
       END AS track_category
FROM track;

-- Categorize purchases as High Value or Normal Purchase.
SELECT invoice_id,
       total,
       CASE
           WHEN total >= 3 THEN 'High Value Customer'
           ELSE 'Normal Purchase'
       END AS purchase_type
FROM invoice;

