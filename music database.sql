--  The number of albums for each artist.
SELECT artist_id, COUNT(*) AS album_count
FROM album
GROUP BY artist_id;

-- Display artists who have more than one album.
SELECT artist_id, COUNT(*) AS album_count
FROM album
GROUP BY artist_id
